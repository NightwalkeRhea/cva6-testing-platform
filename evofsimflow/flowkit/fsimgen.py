"""The files a VC-Z01X campaign is made of.

Two jobs. 'flow.py fsim' generates the strobe, the campaign yml and the
campaign script from the shared templates, and hands the copies to make: the
templates themselves are never edited. evosbst then rewrites the script the
flow generated, once per individual, to run a campaign without make at all.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .ui import FlowError

SUMMARY_REPORT = "fsim_out_summary.rpt"
FULL_REPORTS = ("fsim_out.rpt", "fsim_out_hier.rpt")

# --------------------------------------------------------------- generation


def strobe_text(template: bytes, inject: str, targets: list[str]) -> bytes:
    """`define lines in front of the template, so its `ifndef defaults give
    way. Every target goes through `STROBE_LIST, a multi-line macro, so there
    is no ceiling on the number of observed points."""
    head = "`define STROBE_LIST"
    head += "".join(f" \\\n    $fs_strobe({t});" for t in targets)
    head += f"\n`define INJECT_CYCLE {inject}\n"
    return head.encode() + template


def yml_text(elab: str, fault: str, strobes: list[str]) -> str:
    lines = "".join(f'    "{s}",\n' for s in strobes)
    return f"""\
# GENERATED by flow.py fsim — do not edit by hand.
fsim.inputs:

  optional_elaboration_flags: [{elab}]

  weights: [ {{fault_class: "PT", weight: "1.0"}} ]

  test_coverage:  "(DD * DD_weight + DT * DT_weight + DE * DE_weight + DF * DF_weight + PD * PD_weight + PT * PT_weight)/(Total)"
  fault_coverage: "(DD * DD_weight + DT * DT_weight + DE * DE_weight + DF * DF_weight + PD * PD_weight + PT * PT_weight)/(Total + UB + UI + UR + UT + UU + UO)"

  # Where faults are injected (path relative to ChipTop)
  fault_locations: [
    {{location: "{fault}.**",
     fault_type: "0,1", type_of_fault_location: "PORT", exclude: False}},
  ]

  # Where to observe. The plugin reads strobe_modules only when no strobe file
  # is supplied, and one always is, so this is documentation: the real
  # observation point is the `define STROBE_LIST at the top of the generated
  # strobe.sv.
  strobe_modules: [
{lines}  ]
"""


_SPLIT_BLOCK = """\
# Two tasks per worker, sized from this campaign (added by flow.py).
if {{[catch {{
    set ts_nf [[lindex [getobj_campaigns -campaign {campaign}] 0] getFaultCount]
    if {{![regexp {{(\\d+)\\s*$}} [get_config -global_max_jobs] -> ts_jobs]}} {{
        error "cannot read -global_max_jobs"
    }}
    set ts_size [expr {{min(2046, max(1, int(ceil($ts_nf / (2.0 * $ts_jobs)))))}}]
    set_config -max_faults_per_fsim_task $ts_size
    puts "flow.py: $ts_nf faults, $ts_jobs workers, at most $ts_size per task"
}} ts_err]}} {{
    puts "flow.py: task size left at the default: $ts_err"
}}
"""


def tcl_text(template: str, split: bool, campaign: str) -> str:
    """The campaign script, derived from the flow's template. Two changes:

      - the serial pass gets -no_coats: without it, it reruns a whole
        testability analysis to reprocess a handful of faults;
      - with split, two tasks per worker. Fault and worker counts are both
        read at run time, because the script is copied by tools that change
        the number of workers; if either cannot be read, Z01X's default stands.

    The plugin rewrites the lines holding test1, -exec, -args and -report, so
    the added block uses none of them.
    """
    out: list[str] = []
    serial = split_done = False
    for line in template.split("\n")[:-1] if template.endswith("\n") else template.split("\n"):
        if line.startswith("catch {fsim -selected_status"):
            line = line.replace("fsim -selected_status", "fsim -no_coats -selected_status", 1)
            serial = True
        if split and not split_done and line.startswith("fsim -verbose"):
            out.append(_SPLIT_BLOCK.format(campaign=campaign).rstrip("\n"))
            split_done = True
        out.append(line)
    if not serial or (split and not split_done):
        raise FlowError("the campaign template no longer has the lines this edits:",
                        "the serial 'catch {fsim -selected_status ...}' or 'fsim -verbose'.")
    return "\n".join(out) + "\n"


def strobe_far(fault_path: str, strobe_bases: list[str], tb_top: str) -> bool:
    """True when some observation point is not the faulted module itself. On
    the module's own ports most faults are caught at once and tasks come out
    even; farther away, undetected faults run the whole program and task
    lengths spread."""
    f = fault_path[len("ChipTop."):] if fault_path.startswith("ChipTop.") else fault_path
    for s in strobe_bases:
        if s.startswith(tb_top):
            s = s[len(tb_top):]
        if s.startswith("."):
            s = s[1:]
        if s != f:
            return True
    return False


# ------------------------------------------------- per-individual rewrite

_JOBS_RE = re.compile(r"(-global_max_jobs\s+)(\d+)")
_EXEC_RE = re.compile(r"(-exec\s+)(\S+)")
_ARGS_RE = re.compile(r'(-args\s+")([^"]*)(")', re.S)
_REPORT_RE = re.compile(r"(-report\s+)(\S+)")


@dataclass
class Rewrite:
    simv: Path
    binary: Path
    run_tcl: Path | None
    report_dir: Path
    max_cycles: int
    seed: int
    jobs: int
    coats: bool = True
    keep_reports: set[str] = field(default_factory=lambda: {SUMMARY_REPORT})


def rewrite(template: str, r: Rewrite) -> str:
    """The generated script is self-contained, which is what makes a
    per-individual campaign possible without the build system. Only a handful
    of fields change, and they are rewritten structurally rather than by
    patching paths, so a change of benchmark name does not silently break it."""
    out: list[str] = []
    for line in _logical_lines(template):
        stripped = line.strip()
        if stripped.startswith("set_config") and "-global_max_jobs" in stripped:
            out.append(_JOBS_RE.sub(lambda m: f"{m.group(1)}{r.jobs}", line))
            continue
        if stripped.startswith("create_testcases"):
            line = _EXEC_RE.sub(lambda m: f"{m.group(1)}{r.simv}", line)
            line = _ARGS_RE.sub(
                lambda m: f"{m.group(1)}{rewrite_args(m.group(2), r)}{m.group(3)}", line
            )
            out.append(line)
            continue
        if stripped.startswith("report") and "-report" in stripped:
            m = _REPORT_RE.search(line)
            name = Path(m.group(2)).name if m else ""
            if name not in r.keep_reports:
                continue
            out.append(_REPORT_RE.sub(lambda m: f"{m.group(1)}{r.report_dir / name}", line))
            continue
        if stripped.startswith("fsim ") and "-selected_status" not in stripped and not r.coats:
            out.append(line.rstrip() + " -no_coats")
            continue
        out.append(line)
    return "\n".join(out) + "\n"


def rewrite_args(args: str, r: Rewrite) -> str:
    toks = args.split()
    old_binary = next(
        (t.split("=", 1)[1] for t in toks if t.startswith("+loadmem=")), None
    )

    kept: list[str] = []
    skip = 0
    for i, tok in enumerate(toks):
        if skip:
            skip -= 1
            continue
        if tok == "-ucli" and r.run_tcl is None:
            continue
        if tok == "-do":
            if r.run_tcl is None:
                skip = 1
                continue
            kept += ["-do", str(r.run_tcl)]
            skip = 1
            continue
        if tok.startswith(("+max-cycles=", "+ntb_random_seed", "+vcs+initreg+")):
            continue
        if tok.startswith("+loadmem="):
            kept.append(f"+loadmem={r.binary}")
            continue
        if old_binary and tok == old_binary:
            kept.append(str(r.binary))
            continue
        kept.append(tok)

    # The generated command repeats whole groups of plusargs; keep the first of
    # each. The bare binary path is not a plusarg, so it survives.
    seen: set[str] = set()
    deduped: list[str] = []
    for tok in kept:
        if tok.startswith("+"):
            if tok in seen:
                continue
            seen.add(tok)
        deduped.append(tok)

    extra = [
        f"+max-cycles={r.max_cycles}",
        f"+ntb_random_seed={r.seed}",
        "+vcs+initreg+0",
    ]
    where = next(
        (i for i, t in enumerate(deduped) if t.startswith("+loadmem=")), len(deduped) - 1
    )
    return " ".join(deduped[: where + 1] + extra + deduped[where + 1 :])


def _logical_lines(text: str) -> list[str]:
    """Join backslash continuations so a command is one line to work on."""
    lines: list[str] = []
    buf = ""
    for raw in text.splitlines():
        if raw.rstrip().endswith("\\"):
            buf += raw.rstrip()[:-1]
            continue
        lines.append(buf + raw)
        buf = ""
    if buf:
        lines.append(buf)
    return lines
